const CACHE = "rita-photo-hunt-v2";
const ASSETS = [
  "/photo-treasure-hunt",
  "/photo-treasure-hunt/manifest.webmanifest",
  "/photo-treasure-hunt/icon-192.png",
  "/photo-treasure-hunt/icon-512.png",
];

function inHunt(url) {
  return url.pathname === "/photo-treasure-hunt" || url.pathname.startsWith("/photo-treasure-hunt/");
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(ASSETS))
      .catch(() => undefined),
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys
          .filter((key) => key.startsWith("rita-photo-hunt-") && key !== CACHE)
          .map((key) => caches.delete(key)),
      ),
    ),
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin || !inHunt(url)) return;
  event.respondWith(
    fetch(event.request)
      .then((response) => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(event.request, copy));
        }
        return response;
      })
      .catch(() => caches.match(event.request)),
  );
});
