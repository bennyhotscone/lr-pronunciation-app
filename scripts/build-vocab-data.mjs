/**
 * Build src/data/mandarin-vocab-words.generated.ts from words-1-200.json + known defs.
 */
import { readFileSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const words = JSON.parse(readFileSync(join(__dirname, "words-1-200.json"), "utf8"));

const DEFS = {
  the: { zh: "这个／那个（定冠词）", en: "used before a specific person or thing" },
  be: { zh: "是；成为", en: "to exist or have a particular state" },
  and: { zh: "和；而且", en: "used to connect words or ideas" },
  of: { zh: "……的；属于", en: "used to show connection or belonging" },
  a: { zh: "一个（不定冠词）", en: "used before one non-specific thing" },
  in: { zh: "在……里面", en: "inside a place, area, or period of time" },
  to: { zh: "去；向；到", en: "in the direction of a place or person" },
  have: { zh: "有；拥有", en: "to own, hold, or possess something" },
  it: { zh: "它；这件事", en: "a pronoun for a thing or situation" },
  I: { zh: "我", en: "the speaker referring to himself or herself" },
  that: { zh: "那个；引导从句", en: "used to point to something or introduce a clause" },
  for: { zh: "为了；给；对于", en: "intended to help, benefit, or be used by" },
  you: { zh: "你；你们", en: "the person or people being spoken to" },
  he: { zh: "他", en: "a male person already mentioned" },
  with: { zh: "和；带着；用", en: "together with or using something" },
  on: { zh: "在……上面", en: "touching or supported by a surface" },
  do: { zh: "做；进行", en: "to perform an action or activity" },
  say: { zh: "说；讲", en: "to speak words or express something" },
  this: { zh: "这个；这", en: "used to point to something near or just mentioned" },
  they: { zh: "他们；她们；它们", en: "people, animals, or things already mentioned" },
};

function slugify(word) {
  return String(word)
    .toLowerCase()
    .replace(/'/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "") || "word";
}

const rows = words.map((word, i) => {
  const rank = i + 1;
  const def = DEFS[word] || { zh: "", en: "" };
  const audioFile = `${String(rank).padStart(4, "0")}-${slugify(word)}.mp3`;
  return {
    rank,
    word,
    audioFile,
    zh: def.zh,
    en: def.en,
    group: Math.ceil(rank / 100),
  };
});

const body = `/* Auto-generated by scripts/build-vocab-data.mjs — do not edit by hand. */
import type { MandarinVocabWord } from "./mandarin-vocab";

export const MANDARIN_VOCAB_WORDS: MandarinVocabWord[] = ${JSON.stringify(rows, null, 2)};
`;

writeFileSync(join(__dirname, "..", "src", "data", "mandarin-vocab-words.generated.ts"), body);
console.log("wrote", rows.length, "words");
