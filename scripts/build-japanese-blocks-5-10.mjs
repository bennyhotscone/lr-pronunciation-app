const frequencyWords = JSON.parse(
  readFileSync(join(__dirname, "..", "src", "data", "spoken-english-frequency-5000.json"), "utf8"),
);

function toWord([jp, audio, r, en, m]) {
  return { jp, audio, r, en, m };
}

for (const [blockNum, rows] of Object.entries(WORDS)) {
  const n = Number(blockNum);
  const start = (n - 1) * 50;
  const expected = frequencyWords.slice(start, start + 50);
  if (rows.length !== 50) {
    console.error(`Block ${n}: expected 50 words, got ${rows.length}`);
    process.exit(1);
  }
  for (let i = 0; i < 50; i++) {
    const freq = String(expected[i]).toLowerCase();
    const enFirst = rows[i][3].split("/")[0].trim().toLowerCase();
    if (!enFirst.includes(freq) && freq !== enFirst && !rows[i][3].toLowerCase().includes(freq)) {
      console.warn(`Block ${n} word ${i + 1}: freq "${freq}" vs en "${rows[i][3]}"`);
    }
  }
  const json = rows.map(toWord);
  const path = join(outDir, `block${n}.json`);
  writeFileSync(path, JSON.stringify(json, null, 2) + "\n");
  console.log(`Wrote ${path} (${json.length} words)`);
}
